import { describe, expect, it } from "vitest";
import { AppError } from "../src/middleware/error";
import { generateLicenseKey } from "../src/infra/crypto";
import {
  buildCustomerPortalAccessUrl,
  COMMON_EMAIL_VARIABLES,
  getEmailNotificationContract,
  listEmailNotificationContracts,
  validateEmailNotificationVariables,
  type EmailNotificationContract,
} from "../src/domain/email/contracts";
import {
  EMAIL_PROVIDER_TEMPLATE_REGISTRY,
  getEmailProviderTemplateExample,
  validateEmailProviderTemplateVariables,
  validateResendTemplateVariables,
} from "../src/infra/email/provider-template-registry";

const PRODUCT_ID = "prd_00000000000000000000000000";
const LICENSE_ID = "lic_00000000000000000000000000";
const LICENSE_KEY = "LK-000000-000000-000000-000000-00";

function expectCode(action: () => unknown, code: string): void {
  try {
    action();
    throw new Error(`Expected ${code}`);
  } catch (error) {
    expect(error).toBeInstanceOf(AppError);
    expect((error as AppError).code).toBe(code);
  }
}

function licenseVariables(extra: Record<string, unknown> = {}) {
  return {
    instance_name: "Example Team",
    product_id: PRODUCT_ID,
    product_name: "Example App",
    license_id: LICENSE_ID,
    license_key: LICENSE_KEY,
    license_model: "subscription",
    ...extra,
  };
}

function placeholders(value: string): string[] {
  return [...value.matchAll(/\{\{\{([A-Za-z0-9_]+)\}\}\}/g)].map(
    (match) => match[1],
  );
}

describe("email contract registry", () => {
  it("registers the V1 contracts with the shared public variables", () => {
    const contracts = listEmailNotificationContracts();
    expect(contracts.map((item) => `${item.notificationType}@${item.version}`)).toEqual([
      "customer.license_issued@1",
      "customer.license_recovered@1",
      "customer.license_security_reset@1",
      "customer.portal_access_requested@1",
      "instance.member_invited@1",
    ]);
    expect(COMMON_EMAIL_VARIABLES.map((item) => item.name)).toEqual(["instance_name"]);
    for (const contract of contracts) {
      expect(contract.variables[0]?.name).toBe("instance_name");
      expect(contract.variables.map((item) => item.name)).not.toContain("recipient_email");
      for (const descriptor of contract.variables) {
        expect(descriptor.example).not.toBe("");
      }
      const fixedExample = Object.fromEntries(
        contract.variables.map((descriptor) => [
          descriptor.name,
          descriptor.example,
        ]),
      );
      const validated = validateEmailNotificationVariables(
        contract.notificationType,
        contract.version,
        fixedExample,
        contract.notificationType === "customer.portal_access_requested" ||
          contract.notificationType === "instance.member_invited"
          ? {
              trustedSiteUrl: "https://license.example.com",
              expectedInstanceSlug: "example-team",
            }
          : {},
      );
      expect(() => validateEmailProviderTemplateVariables("resend", validated)).not.toThrow();
    }
  });

  it("accepts valid V1 variables and omits absent optional values", () => {
    expect(
      validateEmailNotificationVariables(
        "customer.license_issued",
        1,
        licenseVariables(),
      ),
    ).toEqual(licenseVariables());
    expect(
      validateEmailNotificationVariables(
        "customer.license_recovered",
        1,
        licenseVariables({
          key_version: 2,
          expires_at: "2026-10-19T10:00:00.000Z",
          updates_until: "2027-10-19T10:00:00Z",
        }),
      ),
    ).toMatchObject({ key_version: 2 });
  });

  it("accepts the license key format generated by real business flows", () => {
    const generatedLicenseKey = generateLicenseKey("LK");
    expect(
      validateEmailNotificationVariables(
        "customer.license_issued",
        1,
        licenseVariables({ license_key: generatedLicenseKey }),
      ),
    ).toMatchObject({ license_key: generatedLicenseKey });
  });

  it("rejects unknown contracts, variables, missing variables, wrong types, enums, formats and lengths", () => {
    expectCode(
      () => getEmailNotificationContract("customer.unknown", 1),
      "EMAIL_NOTIFICATION_CONTRACT_NOT_REGISTERED",
    );
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.license_issued",
          1,
          licenseVariables({ unexpected: "value" }),
        ),
      "EMAIL_CONTRACT_VARIABLE_UNKNOWN",
    );
    const missing = licenseVariables();
    delete (missing as Partial<typeof missing>).license_key;
    expectCode(
      () => validateEmailNotificationVariables("customer.license_issued", 1, missing),
      "EMAIL_CONTRACT_VARIABLE_REQUIRED",
    );
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.license_recovered",
          1,
          licenseVariables({ key_version: "2" }),
        ),
      "EMAIL_CONTRACT_VARIABLE_TYPE_INVALID",
    );
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.license_issued",
          1,
          licenseVariables({ license_model: "trial" }),
        ),
      "EMAIL_CONTRACT_VARIABLE_ENUM_INVALID",
    );
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.license_issued",
          1,
          licenseVariables({ expires_at: "2026-02-30T10:00:00Z" }),
        ),
      "EMAIL_CONTRACT_VARIABLE_FORMAT_INVALID",
    );
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.license_issued",
          1,
          licenseVariables({ product_name: "x".repeat(101) }),
        ),
      "EMAIL_CONTRACT_VARIABLE_LENGTH_INVALID",
    );
  });

  it("builds and validates portal access URLs only against the trusted HTTPS Site URL", () => {
    const trustedSiteUrl = "https://license.example.com/site";
    const accessUrl = buildCustomerPortalAccessUrl({
      trustedSiteUrl,
      instanceSlug: "example-team",
      oneTimeToken: `mlk_${"0".repeat(64)}`,
    });
    expect(accessUrl).toBe(
      `https://license.example.com/site/customer/example-team/auth#token=mlk_${"0".repeat(64)}`,
    );
    expect(
      validateEmailNotificationVariables(
        "customer.portal_access_requested",
        1,
        {
          instance_name: "Example Team",
          access_url: accessUrl,
          expires_at: "2026-10-19T10:15:00.000Z",
        },
        { trustedSiteUrl, expectedInstanceSlug: "example-team" },
      ),
    ).toMatchObject({ access_url: accessUrl });
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.portal_access_requested",
          1,
          {
            instance_name: "Example Team",
            access_url: accessUrl,
            expires_at: "2026-10-19T10:15:00.000Z",
          },
        ),
      "EMAIL_TRUSTED_SITE_URL_REQUIRED",
    );
    expectCode(
      () =>
        validateEmailNotificationVariables(
          "customer.portal_access_requested",
          1,
          {
            instance_name: "Example Team",
            access_url: `https://evil.example/customer/example-team/auth#token=${"0".repeat(64)}`,
            expires_at: "2026-10-19T10:15:00.000Z",
          },
          { trustedSiteUrl, expectedInstanceSlug: "example-team" },
        ),
      "EMAIL_ACCESS_URL_UNTRUSTED",
    );
    for (const untrustedAccessUrl of [
      `https://license.example.com/site/customer/other-team/auth#token=mlk_${"0".repeat(64)}`,
      `https://license.example.com/site/customer/example-team/auth#token=mlk_${"g".repeat(64)}`,
      `https://license.example.com/site/customer/example-team/auth?source=email#token=mlk_${"0".repeat(64)}`,
      `https://user:password@license.example.com/site/customer/example-team/auth#token=mlk_${"0".repeat(64)}`,
    ]) {
      expectCode(
        () =>
          validateEmailNotificationVariables(
            "customer.portal_access_requested",
            1,
            {
              instance_name: "Example Team",
              access_url: untrustedAccessUrl,
              expires_at: "2026-10-19T10:15:00.000Z",
            },
            { trustedSiteUrl, expectedInstanceSlug: "example-team" },
          ),
        "EMAIL_ACCESS_URL_UNTRUSTED",
      );
    }
    expectCode(
      () =>
        buildCustomerPortalAccessUrl({
          trustedSiteUrl,
          instanceSlug: "example-team",
          oneTimeToken: `mlk_${"A".repeat(64)}`,
        }),
      "EMAIL_PORTAL_TOKEN_INVALID",
    );
  });
});

describe("email Provider template example registry", () => {
  it("registers fixed Resend Subject, HTML and Text examples for every contract", () => {
    expect(Object.keys(EMAIL_PROVIDER_TEMPLATE_REGISTRY)).toEqual(["resend"]);
    for (const contract of listEmailNotificationContracts()) {
      const registered = getEmailProviderTemplateExample(
        "resend",
        contract.notificationType,
        contract.version,
      );
      expect(registered.placeholderSyntax).toBe("{{{variable_name}}}");
      expect(registered.fileName).toMatch(/\.resend\.html$/);
      expect(registered.subject.length).toBeGreaterThan(0);
      expect(registered.html).toContain("<!doctype html>");
      expect(registered.text.length).toBeGreaterThan(0);

      const descriptors = new Map(
        (contract as EmailNotificationContract).variables.map((item) => [
          item.name,
          item,
        ]),
      );
      const used = new Set([
        ...placeholders(registered.subject),
        ...placeholders(registered.html),
        ...placeholders(registered.text),
      ]);
      for (const name of used) {
        expect(descriptors.get(name)?.required).toBe(true);
      }
    }
  });

  it("fails fast for unregistered Providers and missing Provider examples", () => {
    expectCode(
      () =>
        getEmailProviderTemplateExample(
          "smtp",
          "customer.license_issued",
          1,
        ),
      "EMAIL_PROVIDER_NOT_REGISTERED",
    );
    expectCode(
      () =>
        getEmailProviderTemplateExample(
          "resend",
          "customer.license_issued",
          2,
        ),
      "EMAIL_PROVIDER_TEMPLATE_EXAMPLE_NOT_REGISTERED",
    );
  });

  it("enforces Resend variable limits only through the Provider layer", () => {
    expect(() =>
      validateEmailProviderTemplateVariables("resend", licenseVariables()),
    ).not.toThrow();
    expectCode(
      () => validateEmailProviderTemplateVariables("smtp", {}),
      "EMAIL_PROVIDER_NOT_REGISTERED",
    );
    expectCode(
      () => validateResendTemplateVariables({ EMAIL: "buyer@example.com" }),
      "EMAIL_PROVIDER_VARIABLE_NAME_RESERVED",
    );
    expectCode(
      () => validateResendTemplateVariables({ "invalid-key": "value" }),
      "EMAIL_PROVIDER_VARIABLE_NAME_INVALID",
    );
    expectCode(
      () => validateResendTemplateVariables({ ["x".repeat(51)]: "value" }),
      "EMAIL_PROVIDER_VARIABLE_NAME_TOO_LONG",
    );
    expectCode(
      () => validateResendTemplateVariables({ value: "x".repeat(2001) }),
      "EMAIL_PROVIDER_VARIABLE_STRING_TOO_LONG",
    );
    expectCode(
      () => validateResendTemplateVariables({ value: Number.MAX_SAFE_INTEGER + 1 }),
      "EMAIL_PROVIDER_VARIABLE_NUMBER_INVALID",
    );
    expectCode(
      () =>
        validateResendTemplateVariables(
          Object.fromEntries(
            Array.from({ length: 51 }, (_, index) => [`value_${index}`, "x"]),
          ),
        ),
      "EMAIL_PROVIDER_VARIABLE_COUNT_EXCEEDED",
    );
  });

  it("requires key_version to be a positive safe integer", () => {
    for (const keyVersion of [-1, 0, 1.5, Number.MAX_SAFE_INTEGER + 1]) {
      expectCode(
        () =>
          validateEmailNotificationVariables(
            "customer.license_recovered",
            1,
            licenseVariables({ key_version: keyVersion }),
          ),
        "EMAIL_CONTRACT_VARIABLE_NUMBER_INVALID",
      );
    }
    expect(() =>
      validateEmailNotificationVariables(
        "customer.license_recovered",
        1,
        licenseVariables({ key_version: 1 }),
      ),
    ).not.toThrow();
  });

  it("does not copy sensitive values into validation errors", () => {
    const secret = "LIC-SECRET-SHOULD-NOT-APPEAR";
    try {
      validateEmailNotificationVariables(
        "customer.license_issued",
        1,
        licenseVariables({ license_key: secret }),
      );
      throw new Error("Expected license key validation to fail");
    } catch (error) {
      const appError = error as AppError;
      expect(appError.message).not.toContain(secret);
      expect(JSON.stringify(appError.details)).not.toContain(secret);
      expect(appError.source).toBeUndefined();
    }

    const misplacedSecret = "LK-SECRET-MISUSED-AS-A-VARIABLE-NAME";
    for (const action of [
      () =>
        validateEmailNotificationVariables(
          "customer.license_issued",
          1,
          licenseVariables({ [misplacedSecret]: "value" }),
        ),
      () => validateResendTemplateVariables({ [misplacedSecret]: "value" }),
    ]) {
      try {
        action();
        throw new Error("Expected variable-name validation to fail");
      } catch (error) {
        const appError = error as AppError;
        expect(appError.message).not.toContain(misplacedSecret);
        expect(JSON.stringify(appError.details)).not.toContain(misplacedSecret);
      }
    }
  });
});
