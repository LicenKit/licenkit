import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const repositoryRoot = fileURLToPath(new URL("../", import.meta.url));
const serverRequire = createRequire(new URL("../apps/server/package.json", import.meta.url));
const Database = serverRequire("better-sqlite3");
const migrationsDirectory = path.join(repositoryRoot, "apps/server/drizzle");
const outputPath = path.join(repositoryRoot, "docs/internal/schema.sql");
const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/generate-schema-review.mjs [--check]");
}

const db = new Database(":memory:");
try {
  db.pragma("foreign_keys = ON");
  const migrations = fs.readdirSync(migrationsDirectory)
    .filter((name) => name.endsWith(".sql"))
    .sort();
  if (migrations.length === 0) throw new Error("No schema migrations were found.");
  for (const migration of migrations) {
    const source = fs.readFileSync(path.join(migrationsDirectory, migration), "utf8");
    db.transaction(() => db.exec(source))();
  }
  const definitions = db.prepare(
    `SELECT sql FROM sqlite_schema
     WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
     ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, name`,
  ).all();
  const header = [
    "-- Generated by node scripts/generate-schema-review.mjs; do not edit by hand.",
    `-- Current schema after all ${migrations.length} migrations through ${migrations.at(-1)}.`,
    "-- This is a maintainer review copy, not a deployment migration.",
    "-- Regenerate with pnpm docs:schema; pnpm test checks that this copy is current.",
  ].join("\n");
  const generated = `${header}\n\nPRAGMA foreign_keys = ON;\n\n`
    + definitions.map(({ sql }) => `${sql.replace(/;\s*$/, "")};`).join("\n\n")
    + "\n";
  if (args.includes("--check")) {
    if (fs.readFileSync(outputPath, "utf8") !== generated) {
      throw new Error("The schema review copy is out of date. Run pnpm docs:schema.");
    }
    console.log(`Schema review copy matches ${migrations.length} migrations.`);
  } else {
    fs.writeFileSync(outputPath, generated);
    console.log(`Updated docs/internal/schema.sql from ${migrations.length} migrations.`);
  }
} finally {
  db.close();
}
